import itertools


# Response and candidate predictors
response = 'Q("Return_10D")'

predictors = [
    'Q("Surprise(%)")',
    'TNX',
    'Oil',
    'Q("Last_Quarter_Change")',
    'Q("Last_Year_Change")',
    'C(Sector)',
    'C(Country)',
    'Q("Surprise(%)"):C(Sector)',
    'Q("Surprise(%)"):Oil',
    'Q("Surprise(%)"):TNX',
    'Oil:C(Sector)',
    'Q("Last_Year_Change"):C(Sector)'
]

# Keep only columns needed for this analysis
required = [
    "Return_10D", "Surprise(%)", "TNX", "Oil",
    "Last_Quarter_Change", "Last_Year_Change",
    "Sector", "Country"
]
df = model_data.dropna(subset=required).copy()

results = []

# Try every combination of predictors
for k in range(1, len(predictors) + 1):
    for subset in itertools.combinations(predictors, k):

        formula = response + " ~ " + " + ".join(subset)

        try:
            fit = smf.ols(formula, data=df).fit()

            results.append({
                "Predictors": ", ".join(subset),
                "Num_Predictors": k,
                "R_squared": fit.rsquared,
                "Adj_R_squared": fit.rsquared_adj,
                "AIC": fit.aic,
                "BIC": fit.bic
            })
        except Exception as e:
            print("Skipped:", formula, e)

results_df = pd.DataFrame(results)

# Best models by each criterion
print("Best model by BIC:")
print(results_df.loc[results_df["BIC"].idxmin()])

print("\nBest model by adjusted R-squared:")
print(results_df.loc[results_df["Adj_R_squared"].idxmax()])

print("\nTop 10 models by BIC:")
print(results_df.nsmallest(10, "BIC").to_string(index=False))