import pandas as pd
import yfinance as yf
import requests
import statsmodels.formula.api as smf

"""Getting data, and cleaning it"""

tnx = yf.download(
    '^TNX',
    start="2021-01-01",
    end="2026-01-01",
    auto_adjust=True
)

# Create a simple two-column dataset
tnx_df = tnx[['Open']].reset_index()
tnx_df.columns = ['Date', 'TNX']

# Ensure dates match your existing dataset
tnx_df['Date'] = pd.to_datetime(tnx_df['Date']).dt.normalize()

oil = yf.download(
    'CL=F',
    start="2021-01-01",
    end="2026-01-01",
    auto_adjust=True
)

# Create a simple two-column dataset
oil_df = oil[['Open']].reset_index()
oil_df.columns = ['Date', 'CL=F']

# Ensure dates match your existing dataset
oil_df['Date'] = pd.to_datetime(oil_df['Date']).dt.normalize()

print(oil_df.head())

url = "https://en.wikipedia.org/wiki/List_of_S%26P_500_companies"

headers = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/130.0.0.0 Safari/537.36"
}

tables = pd.read_html(
    url,
    storage_options=headers
)

tickers = tables[0]["Symbol"].tolist()
tickers = [
    ticker.replace(".", "-")
    for ticker in tickers
]


failed_tickers = ["VYLR", "HONA", "FDXF"]

tickers = [
    ticker for ticker in tickers
    if ticker not in failed_tickers
]





sector_df = tables[0][['Symbol', 'GICS Sector']].copy()

sector_df.columns = ['Ticker', 'Sector']

sector_df['Ticker'] = sector_df['Ticker'].str.replace(
    '.', '-', regex=False
)

sector_df = sector_df[
    ~sector_df['Ticker'].isin(failed_tickers)
]

prices = yf.download(
    tickers,
    start="2023-01-01",
    end="2026-01-01",
    auto_adjust=True
)

prices.columns = prices.columns.to_flat_index()

prices_long = prices.reset_index().melt(
    id_vars=['Date'],
    var_name='Variable',
    value_name='Price'
)

prices_long[['Price Type', 'Ticker']] = pd.DataFrame(
    prices_long['Variable'].tolist(),
    index=prices_long.index
)

prices_long = prices_long.drop(columns='Variable')

prices_long.tail()

close = prices_long.copy()
close = close[close['Price Type'] == 'Close']
close = close.rename(columns={'Price':'Closing_Price'})
close.drop(columns= 'Price Type')

prices_long["price-in-10d"]= prices_long['Price'].shift(-10)
prices_long["Return_10D"] = prices_long["price-in-10d"]/prices_long['Price']-1
prices_long = prices_long[prices_long['Price Type'] == 'Open']
prices_long = prices_long.merge(close, on=['Date', 'Ticker'], how = 'inner')

prices_long["Return_D"] = prices_long["Closing_Price"]/prices_long['Price']-1
prices_long.head()

earnings_list = []

for ticker in tickers:
    temp = yf.Ticker(ticker).get_earnings_dates(limit=25)
    temp = temp.reset_index()
    temp['Ticker'] = ticker
    earnings_list.append(temp)

earnings_df = pd.concat(earnings_list, ignore_index=True)

earnings_df.dropna()

"""Add new columns of last year and last quarter earnings"""

earnings_df['EPS_Last_Quarter'] = (
    earnings_df.groupby('Ticker')['Reported EPS'].shift(1)
)

# EPS from four reports ago (approximately same quarter last year)
earnings_df['EPS_Last_Year'] = (
    earnings_df.groupby('Ticker')['Reported EPS'].shift(4)
)

earnings_df['Last_Quarter_Change'] = earnings_df['Reported EPS']/earnings_df['EPS_Last_Quarter']-1
earnings_df['Last_Year_Change'] = earnings_df['Reported EPS']/earnings_df['EPS_Last_Year']-1

earnings_df['Earnings Date'] = (
    pd.to_datetime(earnings_df['Earnings Date'], utc=True)
      .dt.tz_localize(None)
      .dt.normalize()
)

prices_long['Date'] = (
    pd.to_datetime(prices_long['Date'], utc=True)
      .dt.tz_localize(None)
      .dt.normalize()
)

data = pd.merge(earnings_df, prices_long,
              left_on= ['Ticker', 'Earnings Date'],
              right_on=['Ticker', 'Date'],
              how='inner')

data = pd.merge(data, tnx_df,
                left_on='Date',
                right_on='Date',
                how='inner')

data = data.merge(
    sector_df,
    on='Ticker',
    how='left'
)
data = data.merge(oil_df, on=['Date'], how='inner')

data = data.drop(
    columns=["EPS Estimate", "Price Type_x", "Price Type_y", "price-in-10d"],
    errors="ignore"
)
data= data.rename(columns = {'CL=F':'Oil'})

data.head()

"""Modeling"""

# 1. Clean the data
df = data.copy()

df = df.dropna(subset=[
    "Return_10D",
    "Surprise(%)",
    "TNX",
    "Sector",
    "Ticker",
    "Oil",
    "Return_D",
    'Last_Quarter_Change',
    'Last_Year_Change'
])

# 2. Fit a regression with sector-specific surprise effects
model = smf.ols(
    'Q("Return_10D") ~ C(Sector) * Oil + TNX+ Last_Year_Change * C(Sector)',
    data=df
).fit(cov_type="HC3")

# 3. Inspect results
print(model.summary())