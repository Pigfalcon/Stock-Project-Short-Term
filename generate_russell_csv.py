import pandas as pd
import yfinance as yf
import time
import os
from google.colab import drive

url = "https://tickerinside.com/api/v1/fund/iwm.csv"

holdings = pd.read_csv(url)

print("Rows downloaded:", len(holdings))
print("Columns:", holdings.columns.tolist())
display(holdings.head())

# 1. Connect Google Drive
drive.mount('/content/drive')

folder = '/content/drive/MyDrive/Stock Research'
os.makedirs(folder, exist_ok=True)

output_path = os.path.join(
    folder, 'russell_2000_500m_to_1b.csv'
)
checkpoint_path = os.path.join(
    folder, 'russell_2000_checkpoint.csv'
)

# 2. Get tickers from the existing holdings DataFrame
ticker_col = next(
    (c for c in holdings.columns
     if str(c).strip().lower() in ['ticker', 'symbol']),
    None
)

if ticker_col is None:
    raise ValueError(
        f"Ticker column not found. Available columns: "
        f"{holdings.columns.tolist()}"
    )

tickers = (
    holdings[ticker_col]
    .dropna()
    .astype(str)
    .str.strip()
    .str.replace('.', '-', regex=False)
)

tickers = sorted(set(
    t for t in tickers
    if t and t.lower() not in ['nan', '-', 'cash']
))

# 3. Start fresh so the old Industry column cannot carry over
results_df = pd.DataFrame(
    columns=['Ticker', 'MarketCap', 'Sector', 'Country']
)
completed = set()

# 4. Market-cap range
MIN_CAP = 500_000_000
MAX_CAP = 1_000_000_000

print(f"Checking {len(tickers)} tickers...")

for i, ticker in enumerate(tickers, start=1):
    try:
        info = yf.Ticker(ticker).get_info()

        market_cap = info.get('marketCap')
        sector = info.get('sector') or 'Unknown'
        country = info.get('country') or 'Unknown'

        if market_cap is not None and MIN_CAP <= market_cap <= MAX_CAP:
            new_row = pd.DataFrame([{
                'Ticker': ticker,
                'MarketCap': market_cap,
                'Sector': sector,
                'Country': country
            }])

            results_df = pd.concat(
                [results_df, new_row], ignore_index=True
            )

        completed.add(ticker)

    except Exception as e:
        print(f"Could not retrieve {ticker}: {str(e)[:100]}")

    # Save progress every 25 tickers
    if i % 25 == 0 or i == len(tickers):
        results_df = results_df[
            ['Ticker', 'MarketCap', 'Sector', 'Country']
        ]

        results_df.to_csv(checkpoint_path, index=False)

        print(
            f"Checked {i}/{len(tickers)} | "
            f"Qualifying companies: {len(results_df)}"
        )

    time.sleep(0.3)

# 5. Clean and save final CSV
results_df = (
    results_df
    .drop_duplicates('Ticker')
    .sort_values('Ticker')
    .reset_index(drop=True)
)

results_df.to_csv(output_path, index=False)
results_df.to_csv(checkpoint_path, index=False)

print("\nFinished!")
print("Qualifying companies:", len(results_df))
print("Sector categories:", results_df['Sector'].nunique())
print("\nSector counts:")
print(results_df['Sector'].value_counts(dropna=False))
print("\nSaved to:", output_path)

display(results_df.head(20))
